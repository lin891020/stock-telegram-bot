"""財報公布後的報告 prompt。

這裡的標準比 /analyze 嚴格：/analyze 是學習用的框架示範，
這份是決策用的事實摘要。差別在於——這份的原料是公司自己寫的新聞稿，
所以幾乎所有內容都該是「摘錄」而不是「推論」。
"""

_DISCIPLINE = """
資料紀律（最高優先）：
1. 所有數字必須來自上方提供的資料，並標註來源。嚴禁使用訓練資料中的數字。
2. 管理層說法必須是新聞稿原文的直接引述或忠實翻譯，不得改寫語氣或加油添醋。
   原文沒說的話，一個字都不能加。
3. 財測（guidance）必須是公司自己公布的數字。分析師預估不是財測，不可混用。
4. 數字一律照原文的單位與寫法抄，**嚴禁換算單位**。
   原文寫 $81.6 billion 就寫「816 億美元」或直接寫「81.6 billion 美元」，
   不要自行改成其他量級——實測換算會出錯（$81.6 billion 被寫成 811.5 億、
   $91.0 billion 被寫成 911 億）。百萬韓元、十億美元等單位一併照抄。
   不同幣別的數字不得相比或混寫在同一句。
5. 成長率只能引用原文明寫的，不要自己算。原文沒寫就不要寫。
6. 引用任何成長率時，**必須明講比較基準是哪一期**，寫成「較 2026Q1」「較 2025Q2」
   這種具體期別，不可只寫「較去年同期」「年增」。
   財務表常同時列出季增與年增兩欄（例如「Previous Period」後面那個 Changes(%)
   是季增，「Year to Year Comparison」後面那個才是年增），
   分不清楚是哪一欄就不要引用該成長率，只寫絕對金額。
   實測 SK hynix 的季增 50.9% 曾被誤寫成年增，真正的年增是 256.8%。
7. 新聞稿裡找不到的東西就寫「新聞稿未提及」，不要推測。
"""

BRIEF_SYSTEM = (
    "你是一位財經編輯，負責把公司剛公布的財報新聞稿濃縮成幾行重點。"
    "用繁體中文，只陳述事實，不做投資建議。"
)

BRIEF_PROMPT = """把 {label} 這次財報濃縮成速覽，嚴格照以下格式輸出，不要加標題或結語：

營收：<本季營收與年增率，標幣別與來源；新聞稿未提及則寫「新聞稿未提及」>
獲利：<本季 EPS 或淨利，若有市場預估則寫 beat/miss 與幅度，標來源>
管理層：<新聞稿中管理層原話最關鍵的一句，繁體中文翻譯，用「」框住；沒有則寫「新聞稿無管理層引述」>
財測：<公司自己公布的下季或全年財測數字；沒有則寫「未提供財測」>
一句話：<這季最值得注意的一件事，純事實陳述>

每行不超過兩行文字。數字後面標來源，例如 [SEC 8-K] 或 [yfinance]。
{discipline}"""

FULL_SYSTEM = (
    "你是一位財經分析師，根據公司剛公布的財報新聞稿與財務數據撰寫完整的財報解讀。"
    "用繁體中文，語氣客觀，以摘錄事實為主。"
)

FULL_PROMPT = """根據上方資料，為 {label} 本次財報撰寫完整解讀。

輸出格式規則：
- 使用「## 一、xxx」形式的章節標題
- 用 Markdown 表格呈現數據比較
- 不要使用 emoji、程式碼區塊

章節：
## 一、本季數字
本季營收、獲利、EPS，與上季及去年同期比較。有市場預估就寫 beat/miss。

## 二、管理層怎麼說
直接引述新聞稿中管理層的說法（原文翻譯，用「」框住），並標明是誰說的。
這是本報告最重要的一節——讀者要的就是公司自己的總結與期許。
新聞稿無引述則整節寫「本次新聞稿未包含管理層引述」。

## 三、官方財測
公司自己公布的下季／全年展望數字。逐項列出，標明是公司財測而非分析師預估。
未提供則整節寫「本次未提供財測」。

## 四、數字背後
從財報數字看到的變化（利潤率、成長動能、現金流）。
此節允許推論，但每個推論須以「（推論）」開頭，且必須指明依據哪個數字。

## 五、接下來追蹤什麼
根據本次財報與財測，列出下一季該盯的具體指標。

## 六、本次資料缺漏
原文照抄上方「本次無法取得的資料」清單。不得自行增減。
{discipline}"""


def brief_prompt(label: str) -> str:
    return BRIEF_PROMPT.format(label=label, discipline=_DISCIPLINE)


def full_prompt(label: str) -> str:
    return FULL_PROMPT.format(label=label, discipline=_DISCIPLINE)
